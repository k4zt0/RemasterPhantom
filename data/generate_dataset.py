BY_EXT: dict[str, list] = {}
for s in MAGIC_DB:
    BY_EXT.setdefault(s.extension, []).append(s)


def _sig_brief(sig) -> str:
    return (f"시그니처 0x{sig.signature.hex().upper()}, 오프셋 {sig.offset}, "
            f"길이 {len(sig.signature)}바이트")


# ---------------------------------------------------------------- 시그니처 Q&A
def gen_signature_qa(n_per_sig: int = 48) -> list[dict]:
    out = []
    seen_desc = set()
    for sig in MAGIC_DB:
        if sig.description in seen_desc:
            continue
        seen_desc.add(sig.description)
        hexsig = sig.signature.hex().upper()
        exts = [e for e in BY_EXT if any(d.description != sig.description for d in BY_EXT[e])]
        for _ in range(n_per_sig):
            kind = random.randrange(10)
            if kind == 0:
                q = (f"{sig.description} 파일의 매직 바이트(시그니처)는 무엇인가요? "
                     f"오프셋은 {sig.offset}입니다.")
                a = (f"{sig.description}의 매직 바이트는 0x{hexsig}이며 파일 시작 "
                     f"오프셋 {sig.offset}에서 {len(sig.signature)}바이트입니다. "
                     f"확장자는 .{sig.extension}, MIME는 {sig.mime}입니다. 무결성 "
                     f"검사 시 이 바이트열이 깨져 있으면 헤더 변조(랜섬웨어 1차 신호)로 "
                     f"분류합니다.")
            elif kind == 1:
                q = f"헥스 덤프에서 파일 시작 부분이 {hexsig[:16]}...로 시작합니다. 어떤 파일인가요?"
                a = (f"시작 부분 0x{hexsig[:16]}...는 {sig.description}의 시그니처입니다. "
                     f"전체 시그니처는 0x{hexsig} (오프셋 {sig.offset})이며, "
                     f".{sig.extension} 파일로 식별합니다.")
            elif kind == 2:
                q = f".{sig.extension} 파일이 랜섬웨어로 암호화됐는지 헤더만 보고 어떻게 알 수 있나요?"
                a = (f".{sig.extension}의 정상 시그니처 0x{hexsig}(오프셋 {sig.offset})와 "
                     f"실제 헤더 바이트열을 대조하세요. 불일치하면 TAMPERED로 판정하고, "
                     f"나머지 파일들도 스캔한 뒤 Phantom 프로토콜(격리→락다운→회전→재칸네리)"
                     f"을 발동시켜야 합니다.")
            elif kind == 3:
                q = f"{sig.mime} MIME 타입의 파일 서명을 데이터베이스에 등록하는 표준 절차는?"
                a = (f"시그니처 후보(0x{hexsig})를 최소 3개의 신뢰할 수 있는 샘플에서 "
                     f"검증하고, 오프셋 {sig.offset}, 확장자 .{sig.extension}와 함께 "
                     f"MAGIC_DB에 등록하며, 우연한 매칭 방지를 위해 시그니처 길이가 "
                     f"길수록 신뢰도를 높게 부여합니다.")
            elif kind == 4:
                q = (f"다음 빈칸을 채우세요: \"{sig.description}의 매직 바이트는 "
                     f"0x________ (오프셋 {sig.offset})이다.\"")
                a = (f"정답은 0x{hexsig}입니다. {sig.description}의 시그니처는 "
                     f"오프셋 {sig.offset}의 {len(sig.signature)}바이트열이며 "
                     f"확장자 .{sig.extension}와 대응됩니다.")
            elif kind == 5:
                others = random.sample([s for s in MAGIC_DB if s.description != sig.description], 3)
                opts = [sig] + others
                random.shuffle(opts)
                labels = " ".join(f"({i+1}) 0x{o.signature.hex().upper()}" for i, o in enumerate(opts))
                ans_idx = next(i for i, o in enumerate(opts) if o is sig) + 1
                q = f"{sig.description}의 시그니처로 옳은 것은? {labels}"
                a = (f"정답은 ({ans_idx}) 0x{hexsig}입니다. 오프셋 {sig.offset}, "
                     f"길이 {len(sig.signature)}바이트이며 나머지 선택지는 각각 "
                     f"{', '.join(o.description for o in opts if o is not sig)}의 시그니처입니다.")
            elif kind == 6:
                q = (f".{sig.extension} 파일의 신뢰도(confidence)와 시그니처 길이를 "
                     f"갖고 탐지 정확도를 평가해주세요.")
                a = (f"{sig.description}: 시그니처 길이 {len(sig.signature)}바이트, "
                     f"신뢰도 {sig.confidence:.2f}입니다. 시그니처가 짧을수록(예: 2바이트) "
                     f"우연 매칭 확률이 커지므로 길이 {len(sig.signature)}바이트 기준으로 "
                     f"판정 강도를 조절하고, 확장자 .{sig.extension}·MIME {sig.mime}와 "
                     f"함께 복수 신호로 교차 확인합니다.")
            elif kind == 7:
                q = f".{sig.extension} 확장자 파일의 MIME 타입은 무엇인가요?"
                a = (f".{sig.extension}의 MIME 타입은 {sig.mime}입니다. 시그니처는 "
                     f"0x{hexsig} (오프셋 {sig.offset})이며, 확장자와 MIME·시그니처가 "
                     f"서로 맞지 않으면 확장자 사기(spoofing)를 의심해야 합니다.")
            elif kind == 8:
                q = (f"상황: 보호 디렉터리의 {sig.description} 파일 8개가 동시에 열리지 "
                     f"않는다고 합니다. 헤더 대조 기준값과 첫 조치를 알려주세요.")
                a = (f"기준값은 0x{hexsig} (오프셋 {sig.offset})입니다. 8개 모두 헤더가 "
                     f"깨져 있으면 랜섬웨어 집단 변조로 보고, Sentinel 전수 스캔 → .quarantine "
                     f"격리 → Phantom 락다운 → MASTER CANARY 회전 → 클린 스냅샷 복원 및 "
                     f"재칸네리 순으로 대응합니다.")
            else:
                q = (f"오프셋 {sig.offset}에서 {len(sig.signature)}바이트 시그니처 "
                     f"0x{hexsig}를 가진 파일 형식은 무엇인가요?")
                a = (f"그것은 {sig.description}입니다. 확장자 .{sig.extension}, "
                     f"MIME {sig.mime}이며, 매직 바이트 무결성 검사의 기준 서명으로 "
                     f"사용합니다.")
            out.append({"messages": [
                {"role": "system", "content": SYSTEM},
                {"role": "user", "content": q},
                {"role": "assistant", "content": a}]})
    return out


