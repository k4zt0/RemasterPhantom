def augment_variants(examples: list[dict], times: int = 8) -> list[dict]:
    """질문 표현을 살짝 바꿔 데이터 다양성을 늘린다."""
    openers = ["", "안녕하세요. ", "보안 점검 중입니다. ", "급한 문의입니다. ", "훈련 시나리오: ",
               "침해 대응 훈련용입니다. ", "감사 준비 중입니다. ", "사내 보안 교육용입니다. ",
               "다음 상황을 검토해주세요. ", "업무 중 맞닥뜨린 문제입니다. "]
    closers = ["", " 간단히 요약해주세요.", " 단계별로 알려주세요.", " 주의점도 함께 알려주세요.",
               " 한국어로 답변해주세요.", " 상세히 설명해주세요.", " 표 형식으로 정리해주세요.",
               " 실무에서 바로 적용 가능하게 알려주세요.", " 예시를 들어 설명해주세요.",
               " 신입도 이해할 정도로 설명해주세요."]
    out = []
    for ex in examples:
        out.append(ex)
        for _ in range(times - 1):
            msgs = ex["messages"]
            variant = {"messages": list(msgs)}
            u = msgs[1]["content"]
            variant["messages"][1] = {
                "role": "user",
                "content": random.choice(openers) + u + random.choice(closers)}
            out.append(variant)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/remasterphantom_sft.jsonl")
    ap.add_argument("--n-per-sig", type=int, default=48)
    ap.add_argument("--variants", type=int, default=8)
    args = ap.parse_args()

    parts = [gen_signature_qa(args.n_per_sig), gen_playbooks(), gen_multi_turn()]
    examples = [e for part in parts for e in part]
    examples = augment_variants(examples, args.variants)
    random.shuffle(examples)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        for e in examples:
            f.write(json.dumps(e, ensure_ascii=False) + "\n")
    print(f"saved {len(examples)} examples → {out}")


if __name__ == "__main__":
    main()
